public class Conta {
    private int numero;
    private float saldo;

    public Conta() {

    }

    public int getNumeroConta() {
        return this.numero;
    }

    public void setNumeroConta(int numero) {
        this.numero = numero;
    }

    public float getSaldo() {
        return this.saldo;
    }

    public void setSaldo(float saldo) {
        this.saldo = saldo;
    }
}
